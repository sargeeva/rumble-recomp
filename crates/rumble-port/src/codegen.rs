//! `recomp` command: compile build/main.dol's code to Rust blocks for the
//! `rumble-blocks` crate (see docs/recomp.md, Codegen).
//!
//! A block starts at every function and basic-block start the analysis
//! found, and after every branch (so a call's return lands on one). It runs
//! straight on until a branch (included), an instruction `ops` has no
//! function for (left to the interpreter), the next block's start, or the
//! length limit. Every instruction becomes a call into
//! `rumble_runtime::cpu::ops` with its constant word. The PC is only kept
//! current where something reads it: before a branch (links, `sc`), on a
//! fault (pointing past the faulting instruction, as in the interpreter)
//! and at the block's end.
//!
//! A guest function's blocks are compiled into one Rust function that
//! chains from block to block (`loop { match c.pc { ... } }`) while the
//! dispatcher's instruction budget (`Cpu::budget`) lasts. A block that
//! doesn't fit the budget, or uses the FPU while MSR[FP] is clear, hands
//! back before running. The chain also stops where the dispatcher has to
//! look: after a hardware register access (`Memory::mmio_touched`), after
//! instructions that change or read interrupt or timer state, at an OS-style
//! idle loop (`Cpu::idle_branch`), and on leaving the function.
//!
//! The output is derived from the game, so it stays in build/ and is never
//! committed.

use anyhow::{Context, Result};
use rumble_formats::dol::Dol;
use rumble_recomp::analysis;
use rumble_runtime::cpu::{blocks, ops};
use std::fmt::Write as _;
use std::path::Path;

pub fn run(build_dir: &Path, max_len: u32) -> Result<()> {
    let data = crate::boot::read_dol(build_dir)?;
    let dol = Dol::parse(&data)?;
    let prog = analysis::analyze(&dol);

    let funcs = blocks::plan(&prog, max_len);
    let insns: usize = funcs.iter().flat_map(|f| &f.blocks).map(|b| b.body.len()).sum();

    let mut code = String::new();
    let mut table = String::new();
    let mut blocks = 0usize;
    for fp in &funcs {
        let func = fp.start;
        // When every block returns, the stop check after the match is dead.
        writeln!(code, "#[allow(unreachable_code)]
fn f{func:08x}(c: &mut Cpu, m: &mut Memory) -> Result<(), Fault> {{")?;
        code.push_str("    loop {
        match c.pc {
");
        for block in &fp.blocks {
            let (start, body) = (block.start, &block.body);
            let len = body.len();
            let fpu = block.fpu();
            writeln!(code, "            {start:#010x} => {{")?;
            if fpu {
                writeln!(code, "                if c.budget < {len} || c.msr & MSR_FP == 0 {{ return Ok(()); }}")?;
            } else {
                writeln!(code, "                if c.budget < {len} {{ return Ok(()); }}")?;
            }
            for i in body {
                let handler = ops::handler(i.op).unwrap();
                let kind = if i.is_branch() { "br" } else { "op" };
                writeln!(code, "                {kind}!(c, m, {handler}, {:#010x}, {:#010x}, {:?});", i.addr, i.word, i.op)?;
            }
            let last = body.last().unwrap();
            if !last.is_branch() {
                writeln!(code, "                c.pc = {:#010x};", last.addr + 4)?;
            }
            writeln!(code, "                c.budget -= {len};")?;
            if block.is_idle_loop() {
                writeln!(code, "                c.idle_branch = {:#010x};", last.addr)?;
                code.push_str("                return Ok(());
");
            } else if block.stops_chain() {
                code.push_str("                return Ok(());
");
            }
            code.push_str("            }
");
            let hash = block.hash();
            writeln!(
                table,
                "    Block {{ start: {start:#010x}, len: {len}, fpu: {fpu}, hash: {hash:#018x}, func: {func:#010x}, run: f{func:08x} }},"
            )?;
            blocks += 1;
        }
        code.push_str("            _ => return Ok(()),
        }
        if m.mmio_touched {
            return Ok(());
        }
    }
}

");
    }

    let mut out = String::new();
    out.push_str(
        r#"// Generated by `rumble-port recomp` from build/main.dol. Derived from the
// game: do not edit or commit.

use rumble_recomp::ppc::{Insn, Op::*};
use rumble_runtime::cpu::{blocks::Block, ops, Cpu, MSR_FP};
use rumble_runtime::mem::{Fault, Memory};

/// One instruction. On a fault the PC points past it, as in the interpreter.
macro_rules! op {
    ($c:ident, $m:ident, $f:ident, $addr:literal, $word:literal, $op:ident) => {
        if let Err(e) = ops::$f($c, $m, &Insn { addr: $addr, word: $word, op: $op }) {
            $c.pc = $addr + 4;
            return Err(e);
        }
    };
}

/// A branch (or `sc`/`rfi`): the PC moves past it first, since it is read
/// for the link and the fall-through.
macro_rules! br {
    ($c:ident, $m:ident, $f:ident, $addr:literal, $word:literal, $op:ident) => {
        $c.pc = $addr + 4;
        ops::$f($c, $m, &Insn { addr: $addr, word: $word, op: $op })?;
    };
}

"#,
    );
    out.push_str(&code);
    writeln!(out, "pub static BLOCKS: &[Block] = &[\n{table}];")?;

    let dir = build_dir.join("recomp/gen");
    std::fs::create_dir_all(&dir)?;
    let path = dir.join("blocks.rs");
    std::fs::write(&path, out).with_context(|| format!("writing {}", path.display()))?;
    println!(
        "{blocks} blocks, {insns} of {} instructions ({:.1}%), at most {max_len} long, written to {}",
        prog.stats.insns,
        insns as f64 * 100.0 / prog.stats.insns.max(1) as f64,
        path.display()
    );
    println!("build again (cargo build --release) to compile them in");
    Ok(())
}
